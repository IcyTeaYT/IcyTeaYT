/**
 * Builds src/lib/countryCodes.ts: country name → ISO 3166-1 alpha-2 code, so
 * the conference sheet only needs a country's name.
 *
 *   node scripts/make-country-codes.mjs
 *
 * Names come from the Unicode CLDR data built into Node, restricted to codes
 * the flag set can draw, plus the formal UN names delegates and secretariats
 * actually write ("Russian Federation", "Viet Nam", "Republic of Korea").
 * Generated once and committed, so every browser matches the same way rather
 * than depending on its own copy of the locale data.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const flags = new Set(
  readdirSync(join(ROOT, 'node_modules/flag-icons/flags/4x3'))
    .map((f) => f.replace('.svg', ''))
    .filter((c) => /^[a-z]{2}$/.test(c)),
);

// Must match normaliseCountry() in the generated module.
const normalise = (name) =>
  name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/\bst\.?\s/g, 'saint ')
    .replace(/['’`.]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/^the /, '')
    .trim();

const display = new Intl.DisplayNames(['en'], { type: 'region' });
const map = new Map();
const add = (name, code) => {
  const key = normalise(name);
  if (key && !map.has(key)) map.set(key, code.toUpperCase());
};

for (const code of flags) {
  const name = display.of(code.toUpperCase());
  if (!name || name.toUpperCase() === code.toUpperCase()) continue;
  add(name, code);
  // "Myanmar (Burma)" → also "Myanmar"; "Congo - Kinshasa" handled by aliases.
  add(name.replace(/\s*\([^)]*\)\s*/g, ' '), code);
}

// Formal UN names and common alternatives.
const ALIASES = {
  RU: ['Russian Federation', 'Russia'],
  KR: ['Republic of Korea', 'South Korea', 'Korea'],
  KP: ["Democratic People's Republic of Korea", 'North Korea', 'DPRK'],
  VN: ['Viet Nam', 'Vietnam'],
  TR: ['Türkiye', 'Turkiye', 'Turkey'],
  CI: ["Côte d'Ivoire", 'Cote dIvoire', 'Ivory Coast'],
  US: ['United States of America', 'United States', 'USA', 'US'],
  GB: ['United Kingdom of Great Britain and Northern Ireland', 'United Kingdom', 'UK', 'Great Britain', 'Britain'],
  IR: ['Iran (Islamic Republic of)', 'Islamic Republic of Iran', 'Iran'],
  SY: ['Syrian Arab Republic', 'Syria'],
  LA: ["Lao People's Democratic Republic", 'Laos'],
  BO: ['Bolivia (Plurinational State of)', 'Plurinational State of Bolivia', 'Bolivia'],
  VE: ['Venezuela (Bolivarian Republic of)', 'Bolivarian Republic of Venezuela', 'Venezuela'],
  MD: ['Republic of Moldova', 'Moldova'],
  TZ: ['United Republic of Tanzania', 'Tanzania'],
  CD: ['Democratic Republic of the Congo', 'DR Congo', 'DRC', 'Congo-Kinshasa', 'Congo - Kinshasa'],
  CG: ['Republic of the Congo', 'Congo', 'Congo-Brazzaville', 'Congo - Brazzaville'],
  CZ: ['Czechia', 'Czech Republic'],
  SZ: ['Eswatini', 'Swaziland'],
  MK: ['North Macedonia', 'Macedonia'],
  MM: ['Myanmar', 'Burma'],
  CV: ['Cabo Verde', 'Cape Verde'],
  TL: ['Timor-Leste', 'East Timor'],
  PS: ['State of Palestine', 'Palestine'],
  VA: ['Holy See', 'Vatican', 'Vatican City'],
  FM: ['Micronesia (Federated States of)', 'Federated States of Micronesia', 'Micronesia'],
  BN: ['Brunei Darussalam', 'Brunei'],
  AE: ['United Arab Emirates', 'UAE'],
  NL: ['Netherlands', 'Kingdom of the Netherlands', 'Holland'],
  TW: ['Taiwan', 'Republic of China'],
  CN: ["People's Republic of China", 'China', 'PRC'],
  XK: ['Kosovo'],
  GM: ['Gambia', 'The Gambia'],
  BS: ['Bahamas', 'The Bahamas'],
  KN: ['Saint Kitts and Nevis'],
  LC: ['Saint Lucia'],
  VC: ['Saint Vincent and the Grenadines'],
  BA: ['Bosnia and Herzegovina'],
  TT: ['Trinidad and Tobago'],
  AG: ['Antigua and Barbuda'],
  ST: ['Sao Tome and Principe', 'São Tomé and Príncipe'],
};
for (const [code, names] of Object.entries(ALIASES)) {
  if (!/^[A-Z]{2}$/.test(code) || !flags.has(code.toLowerCase())) continue;
  for (const name of names) {
    // Aliases win over CLDR for the same key — they are the deliberate choice.
    map.set(normalise(name), code);
  }
}
// Historical states have no flag in the set; the closest successor is used
// so a 1962 historical committee still shows a flag rather than a blank chip.
for (const name of ['USSR', 'Soviet Union', 'Union of Soviet Socialist Republics']) map.set(normalise(name), 'RU');

const entries = [...map.entries()].sort((a, b) => a[0].localeCompare(b[0]));
const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: '${v}',`).join('\n');

writeFileSync(
  join(ROOT, 'src/lib/countryCodes.ts'),
  `/**
 * Country name → ISO 3166-1 alpha-2 code. GENERATED by
 * scripts/make-country-codes.mjs — edit that script, not this file.
 */

const CODES: Record<string, string> = {
${body}
};

/** Lowercased, accent-free, punctuation-free form used as the lookup key. */
export function normaliseCountry(name: string): string {
  return name
    .normalize('NFD')
    .replace(/[\\u0300-\\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/\\bst\\.?\\s/g, 'saint ')
    .replace(/['’\`.]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/^the /, '')
    .trim();
}

/**
 * The ISO code for a country name, or null if the name is not recognised.
 * "Russian Federation", "Russia" and "the Russian Federation" all give RU.
 */
export function countryCodeFor(name: string | null | undefined): string | null {
  if (!name) return null;
  const key = normaliseCountry(name);
  if (!key) return null;
  return CODES[key] ?? CODES[normaliseCountry(name.replace(/\\s*\\([^)]*\\)\\s*/g, ' '))] ?? null;
}
`,
);
console.log(`wrote src/lib/countryCodes.ts — ${entries.length} names`);
